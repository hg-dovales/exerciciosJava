public class ClassedaTemperatura {
    public static void main(String[] args){
        double temperatura = 15.00;
        if (temperatura >= 30.00) {
            System.out.println("Temperatura alta!");
        }else if (temperatura >= 20.00) {
            System.out.println("Temperatura agradável!");
        }else {
            System.out.println("Temperatura baixa!");
        }    
    }
}
